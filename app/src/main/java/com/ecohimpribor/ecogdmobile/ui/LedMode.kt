package com.ecohimpribor.ecogdmobile.ui

import androidx.annotation.ColorInt

/**
 * Режимы работы прибора и цвет светодиода-индикатора для каждого.
 * Мигание не используется — все режимы горят ровным светом.
 *
 * Цвета подтверждены официальной документацией ("РЭ_ЭКО-GD", таблица 6):
 * НОРМА — зелёный, ЗАГАЗОВАННОСТЬ (пороги/перегрузка) — красный,
 * НЕИСПРАВНОСТЬ — жёлтый. У реального прибора есть также синий цвет для
 * локального режима «СЕРВИС» (настройка через магнитный ключ) — в
 * приложении не используется, т.к. это не относится к BLE-подключению.
 */
enum class LedMode(
    @ColorInt val color: Int,
    val label: String
) {
    /** Не подключено — светодиод погашен (серый, без свечения). */
    OFF(0xFF3A3A3A.toInt(), label = "Не подключено"),

    /** Включение (инициализация). */
    INIT(0xFF2ECC71.toInt(), label = "Включение (инициализация)"),

    /** Рабочий режим (норма). */
    NORMAL(0xFF2ECC71.toInt(), label = "Рабочий режим (норма)"),

    /** Сработка 1 порога. */
    THRESHOLD_1(0xFFFF3B30.toInt(), label = "Сработка 1 порога"),

    /** Сработка 2 порога. */
    THRESHOLD_2(0xFFFF3B30.toInt(), label = "Сработка 2 порога"),

    /** Максимальная загазованность. */
    MAX_GAS(0xFFFF3B30.toInt(), label = "Максимальная загазованность"),

    /** Неисправность. */
    FAULT(0xFFFFD400.toInt(), label = "Неисправность")
}